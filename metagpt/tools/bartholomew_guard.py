import ast
import hashlib
import json
import re
import time
from typing import Any, Dict, Tuple


class BartholomewSecurityGuard:
    """
    Deterministic AST execution barrier & security gate for MetaGPT multi-agent roles.
    Evaluates proposed shell commands, code generation artifacts, and tool parameters
    before OS syscall boundary execution.
    """

    DESTRUCTIVE_SHELL_PATTERNS = [
        re.compile(
            r"(\/bin\/|\/usr\/bin\/)?rm\s+([-\w\s]*?-[rfRF]+[-\w\s]*?)\s*(/|/\*|~|\$HOME|/etc|/var|/usr|[a-zA-Z]:[\\/])"
        ),
        re.compile(r":\(\)\s*\{\s*:\s*\|\s*:\s*&\s*\}\s*;\s*:"),  # fork bomb
        re.compile(r"mkfs(\.\w+)?\s+/dev/"),
        re.compile(r"dd\s+if=.*?\s+of=(/dev/|[a-zA-Z]:)"),
        re.compile(r">\s*/dev/sd[a-z]"),
        re.compile(r"chmod\s+([-\w\s]*?-R[-\w\s]*?)\s+777\s+(/|/\*)"),
    ]

    CREDENTIAL_PATTERNS = [
        re.compile(r"(ghp_[A-Za-z0-9_]{36,}|github_pat_[A-Za-z0-9_]{82})"),
        re.compile(r"xox[baprs]-[0-9A-Za-z]{10,48}"),
        re.compile(r"sk-[A-Za-z0-9]{32,64}"),
        re.compile(r"-----BEGIN\s+(RSA|EC|DSA|OPENSSH)\s+PRIVATE\s+KEY-----"),
    ]

    def __init__(self, role_name: str = "MetaGPT-Agent", fail_closed: bool = True):
        self.role_name = str(role_name)
        self.fail_closed = fail_closed

    def validate_code(self, code_str: str, is_python_source: bool = True) -> Tuple[bool, str, Dict[str, Any]]:
        """Validates Python code generated by MetaGPT Engineers or Architects before disk emission."""
        t0 = time.perf_counter()

        # 1. Regex check for shell injection / destructive commands
        for pat in self.DESTRUCTIVE_SHELL_PATTERNS:
            if pat.search(code_str):
                receipt = self._build_receipt("VETO", "BTP-AST-001: Destructive shell pattern detected in code", t0)
                if self.fail_closed:
                    raise PermissionError(f"[BTP-METAGPT-VETO]: {receipt['reason']}")
                return False, receipt["reason"], receipt

        # 2. Credential leakage pre-filter
        for pat in self.CREDENTIAL_PATTERNS:
            if pat.search(code_str):
                receipt = self._build_receipt("VETO", "BTP-CRED-001: Secret key or credential pattern detected", t0)
                if self.fail_closed:
                    raise PermissionError(f"[BTP-METAGPT-VETO]: {receipt['reason']}")
                return False, receipt["reason"], receipt

        # 3. Python AST parsing (when evaluating Python code artifacts)
        if is_python_source:
            try:
                tree = ast.parse(code_str)
            except SyntaxError as e:
                receipt = self._build_receipt("VETO", f"BTP-AST-SYNTAX: Syntax error: {str(e)}", t0)
                if self.fail_closed:
                    raise PermissionError(f"[BTP-METAGPT-VETO]: {receipt['reason']}")
                return False, receipt["reason"], receipt

            # Walk AST nodes to block untrusted dynamic eval
            for node in ast.walk(tree):
                if isinstance(node, ast.Call):
                    func_name = ""
                    if isinstance(node.func, ast.Name):
                        func_name = node.func.id
                    elif isinstance(node.func, ast.Attribute):
                        func_name = node.func.attr

                    if func_name in ("exec", "eval") and node.args:
                        if not isinstance(node.args[0], ast.Constant):
                            receipt = self._build_receipt(
                                "VETO", "BTP-AST-003: Dynamic untrusted exec/eval invocation", t0
                            )
                            if self.fail_closed:
                                raise PermissionError(f"[BTP-METAGPT-VETO]: {receipt['reason']}")
                            return False, receipt["reason"], receipt

        receipt = self._build_receipt("ALLOW", "AST invariants verified successfully", t0)
        return True, "Code passed deterministic AST invariant gate", receipt

    def validate_command(self, cmd_str: str) -> Tuple[bool, str, Dict[str, Any]]:
        """Validates shell execution commands run by MetaGPT QA or DevOps roles."""
        t0 = time.perf_counter()

        for pat in self.DESTRUCTIVE_SHELL_PATTERNS:
            if pat.search(cmd_str):
                receipt = self._build_receipt(
                    "VETO", f"BTP-SHELL-001: Destructive shell command blocked: {cmd_str[:60]}", t0
                )
                if self.fail_closed:
                    raise PermissionError(f"[BTP-METAGPT-VETO]: {receipt['reason']}")
                return False, receipt["reason"], receipt

        receipt = self._build_receipt("ALLOW", "Command verified safe", t0)
        return True, "Command safe", receipt

    def wrap_action(self, action_instance: Any) -> Any:
        """Wraps a MetaGPT Action to intercept run execution."""
        orig_run = getattr(action_instance, "run", None)
        if not orig_run:
            return action_instance

        def guarded_run(*args: Any, **kwargs: Any) -> Any:
            payload_str = " ".join(str(a) for a in args) + " " + " ".join(f"{k}={v}" for k, v in kwargs.items())
            self.validate_command(payload_str)
            result = orig_run(*args, **kwargs)
            if isinstance(result, str) and result.strip():
                self.validate_code(result, is_python_source=False)
            return result

        action_instance.run = guarded_run
        return action_instance

    def _build_receipt(self, verdict: str, reason: str, start_time: float) -> Dict[str, Any]:
        latency_us = (time.perf_counter() - start_time) * 1_000_000
        timestamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        leaf_data = {
            "role": self.role_name,
            "verdict": verdict,
            "reason": reason,
            "latency_us": round(latency_us, 2),
            "timestamp": timestamp,
            "standard": "RFC 8785 Merkle",
        }
        canonical_bytes = json.dumps(leaf_data, sort_keys=True, separators=(",", ":")).encode("utf-8")
        receipt_hash = hashlib.sha256(canonical_bytes).hexdigest()
        leaf_data["receipt_hash"] = receipt_hash
        return leaf_data
